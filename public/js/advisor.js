/**
 * Gemini AI Financial Advisor & Action Plan Manager
 */

const Advisor = {
  isSending: false,

  init() {
    this.bindEvents();
    AppState.on('dataLoaded', () => {
      this.loadChat();
      this.loadActionPlans();
    });
  },

  bindEvents() {
    const sendBtn = document.getElementById('chat-send-btn');
    const inputField = document.getElementById('chat-input-text');
    const clearChatBtn = document.getElementById('chat-clear-btn');
    const genPlanBtn = document.getElementById('btn-generate-ai-plan');

    if (sendBtn) {
      sendBtn.addEventListener('click', () => this.sendMessage());
    }

    if (inputField) {
      inputField.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' && !e.shiftKey) {
          e.preventDefault();
          this.sendMessage();
        }
      });
    }

    if (clearChatBtn) {
      clearChatBtn.addEventListener('click', async () => {
        if (confirm('Clear entire conversation history?')) {
          await API.clearChatHistory();
          this.loadChat();
        }
      });
    }

    if (genPlanBtn) {
      genPlanBtn.addEventListener('click', async () => {
        try {
          genPlanBtn.disabled = true;
          genPlanBtn.innerHTML = '<span class="spinner"></span> Generating with Gemini...';
          await API.generateActionPlan();
          await this.loadActionPlans();
          alert('✨ New Personalized CIBIL Action Plan successfully generated by Gemini AI!');
        } catch (e) {
          alert('Failed to generate action plan: ' + e.message);
        } finally {
          genPlanBtn.disabled = false;
          genPlanBtn.innerHTML = '✨ Generate AI Action Plan';
        }
      });
    }

    // Quick chips
    document.querySelectorAll('.quick-chip').forEach(chip => {
      chip.addEventListener('click', () => {
        const text = chip.getAttribute('data-prompt') || chip.textContent.trim();
        const input = document.getElementById('chat-input-text');
        if (input) {
          input.value = text;
          this.sendMessage();
        }
      });
    });
  },

  async loadChat() {
    const container = document.getElementById('chat-messages-container');
    if (!container) return;

    try {
      const data = await API.getChatHistory();
      container.innerHTML = '';

      if (data.messages && data.messages.length > 0) {
        data.messages.forEach(msg => {
          this.appendMessage(msg.role, msg.content, null);
        });
      } else {
        // Welcome message
        this.appendMessage('assistant', `Namaste! 🙏 I am your **Gemini Credit Strategist**.\n\nAsk me anything about boosting your CIBIL score, lowering your credit card utilization, optimizing your Debt-to-Income (DTI) ratio, or disputing errors with Indian credit bureaus.`, 'Gemini AI');
      }

      container.scrollTop = container.scrollHeight;
    } catch (err) {
      console.error('Failed to load chat:', err);
    }
  },

  async sendMessage() {
    const inputField = document.getElementById('chat-input-text');
    const sendBtn = document.getElementById('chat-send-btn');
    if (!inputField || this.isSending) return;

    const message = inputField.value.trim();
    if (!message) return;

    inputField.value = '';
    this.isSending = true;
    if (sendBtn) {
      sendBtn.disabled = true;
      sendBtn.innerHTML = '<span class="spinner"></span>';
    }

    // Append user message immediately
    this.appendMessage('user', message, null);

    // Append temporary typing indicator
    const typingId = 'typing-' + Date.now();
    const container = document.getElementById('chat-messages-container');
    const typingEl = document.createElement('div');
    typingEl.id = typingId;
    typingEl.className = 'chat-bubble chat-bubble-assistant animate-fade-in';
    typingEl.innerHTML = `<i>Aarav is analyzing your credit data with Gemini AI...</i> <span class="spinner" style="margin-left: 6px;"></span>`;
    container.appendChild(typingEl);
    container.scrollTop = container.scrollHeight;

    try {
      const res = await API.sendChatMessage(message);
      const typingNode = document.getElementById(typingId);
      if (typingNode) typingNode.remove();

      this.appendMessage('assistant', res.reply, res.source);
    } catch (err) {
      const typingNode = document.getElementById(typingId);
      if (typingNode) typingNode.remove();

      this.appendMessage('assistant', `⚠️ Sorry, I encountered an issue processing your query: ${err.message}. Please try again.`, 'System Alert');
    } finally {
      this.isSending = false;
      if (sendBtn) {
        sendBtn.disabled = false;
        sendBtn.innerHTML = 'Send';
      }
    }
  },

  appendMessage(role, content, source) {
    const container = document.getElementById('chat-messages-container');
    if (!container) return;

    const bubble = document.createElement('div');
    const isAssistant = role === 'assistant';
    bubble.className = `chat-bubble ${isAssistant ? 'chat-bubble-assistant' : 'chat-bubble-user'} animate-fade-in`;

    // Simple markdown formatting
    let formattedContent = this.formatMarkdown(content);

    let html = `<div>${formattedContent}</div>`;
    if (isAssistant && source) {
      html += `<div class="chat-source-tag"><span class="badge-dot" style="color: #6366f1;"></span> ${source}</div>`;
    }

    bubble.innerHTML = html;
    container.appendChild(bubble);
    container.scrollTop = container.scrollHeight;
  },

  formatMarkdown(text) {
    if (!text) return '';
    let out = text
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/### (.*?)\n/g, '<h3>$1</h3>')
      .replace(/#### (.*?)\n/g, '<h4>$1</h4>')
      .replace(/\*\*(.*?)\*\*/g, '<b>$1</b>')
      .replace(/\*(.*?)\*/g, '<i>$1</i>')
      .replace(/`([^`]+)`/g, '<code style="background: rgba(255,255,255,0.08); padding: 2px 6px; border-radius: 4px; font-family: monospace;">$1</code>')
      .replace(/^\* (.*$)/gm, '<li>$1</li>')
      .replace(/^• (.*$)/gm, '<li>$1</li>');

    // Wrap list items
    out = out.replace(/(<li>.*?<\/li>)/gs, '<ul>$1</ul>');
    out = out.replace(/\n\n/g, '<br><br>');
    return out;
  },

  async loadActionPlans() {
    const container = document.getElementById('action-plans-list');
    const progressEl = document.getElementById('action-plans-progress');
    const pointsEarnedEl = document.getElementById('action-points-earned');
    if (!container) return;

    try {
      const data = await API.getActionPlans();
      const plans = data.plans || [];

      if (progressEl) {
        progressEl.textContent = `${data.completedCount} of ${data.totalCount} Completed`;
      }
      if (pointsEarnedEl) {
        pointsEarnedEl.textContent = `+${data.totalImpactEarned} pts Earned`;
      }

      if (plans.length === 0) {
        container.innerHTML = `<div class="text-dim" style="padding: 2rem; text-align: center;">No action items found. Click "Generate AI Action Plan" to produce a tailored roadmap.</div>`;
        return;
      }

      container.innerHTML = plans.map(p => {
        const isDone = Boolean(p.is_completed);
        const steps = p.action_steps || [];
        const priorityClass = p.priority === 'High' ? 'badge-rose' : (p.priority === 'Medium' ? 'badge-amber' : 'badge-neutral');

        return `
          <div class="action-card ${isDone ? 'completed' : ''}" id="card-plan-${p.id}">
            <div class="action-checkbox ${isDone ? 'checked' : ''}" onclick="Advisor.togglePlan('${p.id}')">
              ${isDone ? '✓' : ''}
            </div>
            <div class="action-content">
              <div class="action-header">
                <span class="action-title">${p.title}</span>
                <div style="display: flex; gap: 0.4rem; align-items: center;">
                  <span class="badge ${priorityClass}">${p.priority}</span>
                  <span class="badge badge-emerald">+${p.impact_points} pts</span>
                </div>
              </div>
              <p class="action-desc">${p.description}</p>
              ${steps.length > 0 ? `
                <ul class="action-steps-list">
                  ${steps.map(s => `<li>${s}</li>`).join('')}
                </ul>
              ` : ''}
              <div style="font-size: 0.72rem; color: var(--text-dim); margin-top: 0.4rem;">
                ${p.phase} • Category: ${p.category}
              </div>
            </div>
          </div>
        `;
      }).join('');
    } catch (err) {
      console.error('Failed to load action plans:', err);
    }
  },

  async togglePlan(planId) {
    try {
      const res = await API.toggleActionPlan(planId);
      await this.loadActionPlans();
      await AppState.refreshProfile();

      if (res.is_completed) {
        this.showToast(`🎉 Action completed! Your score increased by +${res.impact_points} points!`);
      }
    } catch (err) {
      alert('Failed to update action plan: ' + err.message);
    }
  },

  showToast(message) {
    let toast = document.getElementById('app-toast');
    if (!toast) {
      toast = document.createElement('div');
      toast.id = 'app-toast';
      toast.style.cssText = `
        position: fixed;
        bottom: 2rem;
        right: 2rem;
        background: #10b981;
        color: #fff;
        font-weight: 700;
        font-size: 0.92rem;
        padding: 0.9rem 1.4rem;
        border-radius: 10px;
        box-shadow: 0 8px 24px rgba(16, 185, 129, 0.4);
        z-index: 9999;
        transition: all 0.3s cubic-bezier(0.16, 1, 0.3, 1);
        transform: translateY(100px);
        opacity: 0;
      `;
      document.body.appendChild(toast);
    }

    toast.textContent = message;
    toast.style.transform = 'translateY(0)';
    toast.style.opacity = '1';

    setTimeout(() => {
      toast.style.transform = 'translateY(100px)';
      toast.style.opacity = '0';
    }, 3500);
  }
};

window.Advisor = Advisor;
